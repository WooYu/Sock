import { expect, test } from './fixtures/test'
import { readFile } from 'node:fs/promises'
import { openResearch } from './fixtures/chart-workbench'

test('forecast roles filter notes and retain the cited rule source', async ({ page }, info) => {
  await page.goto('/knowledge?view=notes')
  await expect(page.getByRole('heading', { name: '笔记标签目录' })).toBeVisible()
  await page.getByRole('combobox', { name: '预估作用', exact: true }).selectOption('entry')
  await page.getByRole('textbox', { name: '搜索笔记与标签' }).fill('买股原则2.md')
  await page.getByRole('button', { name: /^查看标签：/ }).first().click()
  const roles = page.getByRole('region', { name: '笔记的预估作用', exact: true })
  await expect(roles).toContainText('入场条件')
  await roles.getByText(/查看原文依据/).first().click()
  await expect(roles).toContainText('日MA20下方的新参与过滤')
  await expect(roles.locator('blockquote').first()).toBeVisible()
  await roles.scrollIntoViewIfNeeded()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.screenshot({ path: `artifacts/forecast-note-roles-${info.project.name}.png` })
  await page.getByRole('button', { name: '重置标签筛选' }).click()
  await expect(page.getByRole('combobox', { name: '预估作用', exact: true })).toHaveValue('')
  const downloaded = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出标签与历史', exact: true }).click()
  const download = await downloaded
  const path = info.outputPath('forecast-role-export.json')
  await download.saveAs(path)
  const exported = JSON.parse(await readFile(path, 'utf8'))
  const source = exported.records.find((record: { id: string }) => record.id === 'note:买股原则2.md')
  const classification = exported.forecastRoles.records.find((record: { id: string }) => record.id === source.id)
  expect(exported.taxonomy.map((dimension: { id: string }) => dimension.id)).toEqual(['kind', 'topic'])
  expect(classification).toMatchObject({ sourceHash: source.sourceHash, tagVersion: source.version })
  expect(classification.roles).toContainEqual(expect.objectContaining({ role: 'entry', status: 'defined', ruleIds: expect.arrayContaining(['daily_ma20_entry_filter']) }))
  expect(classification.roles.find((role: { role: string }) => role.role === 'entry').evidence.length).toBeGreaterThan(0)
})

test('automatic forecasts show adopted and unavailable note conditions without hiding prices', async ({ page }, info) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/?example=1')
  await openResearch(page)
  const panel = page.getByRole('region', { name: '自动 MA/BOLL 预测', exact: true })
  const conditions = panel.getByRole('region', { name: '笔记预估条件核对', exact: true })
  await expect(conditions).toBeVisible({ timeout: 30000 })
  await conditions.getByText(/未采用的条件 ·/).click()
  await expect(conditions).toContainText('日MA20下方的新参与过滤')
  await expect(conditions).toContainText('条件影响价位用途与风险判断')
  await expect(panel.getByRole('table', { name: /日线 MA\/BOLL参考位/ })).toBeVisible()
  await conditions.scrollIntoViewIfNeeded()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.screenshot({ path: `artifacts/forecast-note-conditions-${info.project.name}.png` })
  expect(errors).toEqual([])
})
