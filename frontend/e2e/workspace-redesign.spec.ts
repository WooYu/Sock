import { expect, test, type Page } from './fixtures/test'
import { startDrawing, openResearch } from './fixtures/chart-workbench'
import { createPreviewData, loadPreviewSeries } from '../src/features/research/preview-data'
import { aggregateCandles } from '../src/features/chart/chart-math'
import type { ChartPeriod } from '../src/features/chart/chart-periods'

const sample = createPreviewData()
async function mockMarket(page: Page) {
  await page.route('**/api/knowledge/rules', route => route.fulfill({ json: [] }))
  await page.route('**/api/market/stocks/*/snapshot', route => route.fulfill({ json: { ...sample.market, adjustment: 'qfq' } }))
  await page.route('**/api/market/stocks/*/candles?*', async route => {
    const url = new URL(route.request().url()), period = url.searchParams.get('period') as ChartPeriod
    const preview = await loadPreviewSeries('DEMO', period)
    return route.fulfill({ json: { ...preview, adjustment: url.searchParams.get('adjustment') ?? 'none', bars: ['day', 'week', 'month', 'quarter', 'year'].includes(period) ? aggregateCandles(sample.market.dailyCandles, period) : preview.bars } })
  })
}

test.beforeEach(async ({ page }) => { await mockMarket(page) })

