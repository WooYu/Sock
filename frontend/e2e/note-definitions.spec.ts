import { test, expect } from './fixtures/test'
import { join } from 'node:path'
import { tmpdir } from 'node:os'

test('reading view reveals secondary actions and purpose editing only when requested', async ({ page }, info) => {
  let extractionRequests = 0
  page.on('request', request => { if (request.url().includes('/api/note-tag-extraction')) extractionRequests++ })
  await page.goto('/knowledge?view=notes')
  const detail = page.getByRole('region', { name: '标签详情', exact: true })
  await expect(detail.getByRole('button', { name: '编辑标签', exact: true })).toBeVisible()
  await expect(detail.getByRole('button', { name: '补充说明', exact: true })).not.toBeVisible()
  await expect(detail.getByRole('button', { name: 'AI 重新提取标签', exact: true })).not.toBeVisible()
  const more = detail.locator('.nt-secondary-actions > summary')
  await more.focus()
  await page.keyboard.press('Enter')
  await expect(detail.getByRole('button', { name: '补充说明', exact: true })).toBeVisible()
  await expect(detail.getByRole('button', { name: 'AI 重新提取标签', exact: true })).toBeVisible()
  expect(extractionRequests).toBe(0)
  await detail.getByRole('button', { name: '补充说明', exact: true }).click()
  await expect(info.project.name === 'mobile' ? page.getByRole('button', { name: '关闭标签编辑' }) : page.getByRole('dialog').getByLabel('补充说明', { exact: true })).toBeFocused()
  await page.getByRole('button', { name: '取消标签编辑' }).click()
  await more.click()
  await expect(detail.getByRole('button', { name: '补充说明', exact: true })).not.toBeVisible()
  await page.getByRole('textbox', { name: '搜索笔记与标签' }).fill('01-ma-golden-cross.md')
  const purpose = detail.locator('.nt-purpose-disclosure > summary').filter({ hasText: '入场条件' })
  await expect(detail.getByRole('button', { name: '补充定义：入场条件' })).not.toBeVisible()
  await purpose.focus()
  await page.keyboard.press('Enter')
  await expect(detail.getByRole('button', { name: '补充定义：入场条件' })).toBeVisible()
  await expect(detail.getByRole('link', { name: '查看原文 ↗' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
})

test('note definitions keep browsing context, survive reload, and retain read-only history', async ({ page }, info) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/knowledge?view=notes')
  await expect(page).toHaveTitle(/笔记标签/)
  const search = page.getByRole('textbox', { name: '搜索笔记与标签' })
  await search.fill('01-ma-golden-cross.md')
  await page.getByRole('button', { name: '查看标签：均线金叉', exact: true }).click()
  await page.locator('.nt-purpose-disclosure > summary').filter({ hasText: '入场条件' }).click()
  await page.getByRole('button', { name: '补充定义：入场条件' }).click()
  let editor = page.getByRole('dialog')
  await expect(info.project.name === 'mobile' ? editor.getByRole('button', { name: '关闭定义编辑' }) : editor.getByLabel('条件或计算方法')).toBeFocused()
  await editor.getByLabel('条件或计算方法').fill('MA5 向上穿越 MA20，以收盘数据判断。')
  await editor.getByRole('button', { name: '保存草稿' }).click()
  await expect(editor).not.toBeVisible()
  await expect(search).toHaveValue('01-ma-golden-cross.md')
  const purposes = page.getByRole('region', { name: '笔记的预估作用', exact: true })
  await expect(purposes).toContainText('定义草稿')
  await page.reload()
  await search.fill('01-ma-golden-cross.md')
  await page.getByRole('button', { name: '查看标签：均线金叉', exact: true }).click()
  await page.locator('.nt-purpose-disclosure > summary').filter({ hasText: '入场条件' }).click()
  await page.getByRole('button', { name: '编辑定义：入场条件' }).click()
  editor = page.getByRole('dialog')
  await expect(editor.getByLabel('条件或计算方法')).toHaveValue('MA5 向上穿越 MA20，以收盘数据判断。')
  await editor.getByLabel('适用周期', { exact: true }).fill('日线收盘')
  await editor.getByLabel('适用场景', { exact: true }).fill('上涨趋势，成交量温和放大。')
  await editor.getByLabel('失效或退出条件').fill('收盘重新跌破 MA20。')
  await editor.screenshot({ path: join(tmpdir(), `stock-definition-editor-${info.project.name}.png`) })
  await editor.getByRole('button', { name: '保存并标记待验证' }).click()
  await expect(purposes).toContainText('已定义、待验证')
  await page.getByRole('button', { name: '更多筛选' }).click()
  await page.getByRole('combobox', { name: '定义进度' }).selectOption('ready')
  await expect(page.getByRole('button', { name: '查看标签：均线金叉', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '移除筛选：已定义、待验证' }).click()
  await purposes.scrollIntoViewIfNeeded()
  await page.screenshot({ path: join(tmpdir(), `stock-definition-saved-${info.project.name}.png`) })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.getByRole('tab', { name: '版本历史', exact: true }).click()
  await page.getByRole('button', { name: '查看标签 v1', exact: true }).click()
  await expect(page.getByText('历史标签版本，只读', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '补充定义：入场条件' })).toHaveCount(0)
  expect(errors).toEqual([])
})

test('dirty edits require explicit discard and pagination keeps the detail in the visible list', async ({ page }) => {
  await page.goto('/knowledge?view=notes')
  await page.getByRole('button', { name: '下一页', exact: true }).click()
  const list = page.getByRole('region', { name: '笔记目录', exact: true })
  await expect(list.getByRole('button', { name: /^查看标签：/ }).first()).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('textbox', { name: '搜索笔记与标签' }).fill('01-ma-golden-cross.md')
  await page.locator('.nt-purpose-disclosure > summary').filter({ hasText: '入场条件' }).click()
  await page.getByRole('button', { name: '补充定义：入场条件' }).click()
  const editor = page.getByRole('dialog')
  await editor.getByLabel('条件或计算方法').fill('尚未保存')
  await page.evaluate(() => window.history.back())
  await expect(editor.getByRole('button', { name: '继续编辑' })).toBeFocused()
  await editor.getByRole('button', { name: '继续编辑' }).click()
  await expect(editor.getByLabel('条件或计算方法')).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(editor.getByRole('button', { name: '放弃修改' })).toBeVisible()
  await editor.getByRole('button', { name: '继续编辑' }).click()
  await expect(editor.getByLabel('条件或计算方法')).toHaveValue('尚未保存')
  await editor.getByRole('button', { name: '取消定义编辑' }).click()
  await editor.getByRole('button', { name: '放弃修改' }).click()
  await expect(editor).not.toBeVisible()
  await expect(page.getByRole('button', { name: '补充定义：入场条件' })).toBeVisible()
})
