test('reading shows purposes directly and one entry reveals editing tools without AI requests', async ({ page }, info) => {
  let extractionRequests = 0
  page.on('request', request => { if (request.url().includes('/api/note-tag-extraction')) extractionRequests++ })
  await page.goto('/knowledge?view=notes')
  await page.getByRole('textbox', { name: '搜索笔记与标签' }).fill('01-ma-golden-cross.md')
  const detail = page.getByRole('region', { name: '标签详情', exact: true })
  await expect(detail.getByRole('button')).toHaveCount(1)
  await expect(detail.locator('.nt-purpose-heading')).toContainText(['入场条件'])
  await expect(detail.locator('.nt-purpose-body').first()).toBeVisible()
  await detail.getByRole('button', { name: '编辑笔记', exact: true }).click()
  await expect(detail.getByRole('button', { name: '标签与补充说明', exact: true })).toBeVisible()
  await expect(detail.getByRole('button', { name: '编辑用途与定义' })).toBeVisible()
  const actions = detail.locator('.nt-edit-basics .kw-button')
  const bounds = await actions.evaluateAll(elements => elements.map(element => { const rect = element.getBoundingClientRect(); return { y: rect.y, height: rect.height } }))
  expect(bounds.every(box => box.height >= 44)).toBe(true)
  expect(new Set(bounds.map(box => box.y)).size).toBe(1)
  const heading = detail.locator('.nt-card-heading').first()
  const title = (await heading.locator('h4').boundingBox())!, button = (await heading.getByRole('button').boundingBox())!
  expect(Math.abs(title.y + title.height / 2 - button.y - button.height / 2)).toBeLessThan(1)
  await detail.screenshot({ path: info.outputPath('note-editing-actions.png') })
  expect(extractionRequests).toBe(0)
  await detail.getByRole('button', { name: '完成编辑', exact: true }).click()
  await expect(detail.getByRole('button')).toHaveCount(1)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
})

test('note definitions keep browsing context, survive reload, and retain read-only history', async ({ page }, info) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/knowledge?view=notes')
  await expect(page).toHaveTitle(/笔记标签/)
  const search = page.getByRole('textbox', { name: '搜索笔记与标签' })
  await search.fill('01-ma-golden-cross.md')
  await page.getByRole('button', { name: '查看标签：均线金叉', exact: true }).click()
  await page.getByRole('button', { name: '编辑笔记', exact: true }).click()
  await page.getByRole('button', { name: '编辑用途与定义' }).click()
  let editor = page.getByRole('dialog')
  await expect(info.project.name === 'mobile' ? editor.getByRole('button', { name: '关闭定义编辑' }) : editor.getByRole('combobox', { name: '用途', exact: true })).toBeFocused()
  await editor.getByLabel('条件或计算方法').fill('MA5 向上穿越 MA20，以收盘数据判断。')
  await editor.getByRole('button', { name: '保存草稿' }).click()
  await expect(editor).not.toBeVisible()
  await expect(search).toHaveValue('01-ma-golden-cross.md')
  const purposes = page.getByRole('region', { name: '笔记的预估作用', exact: true })
  await expect(purposes).toContainText('定义草稿')
  await page.reload()
  await search.fill('01-ma-golden-cross.md')
  await page.getByRole('button', { name: '查看标签：均线金叉', exact: true }).click()
  await page.getByRole('button', { name: '编辑笔记', exact: true }).click()
  await page.getByRole('button', { name: '编辑用途与定义' }).click()
  editor = page.getByRole('dialog')
  await expect(editor.getByLabel('条件或计算方法')).toHaveValue('MA5 向上穿越 MA20，以收盘数据判断。')
  await editor.getByLabel('适用周期', { exact: true }).fill('日线收盘')
  await editor.getByLabel('适用场景', { exact: true }).fill('上涨趋势，成交量温和放大。')
  await editor.getByLabel('失效或退出条件').fill('收盘重新跌破 MA20。')
  await editor.screenshot({ path: join(tmpdir(), `stock-definition-editor-${info.project.name}.png`) })
  await editor.getByRole('button', { name: '保存并标记待验证' }).click()
  await expect(purposes).toContainText('已定义、待验证')
  await page.getByRole('button', { name: '完成编辑', exact: true }).click()
  for (const text of ['MA5 向上穿越 MA20，以收盘数据判断。', '日线收盘', '上涨趋势，成交量温和放大。', '收盘重新跌破 MA20。']) await expect(purposes.getByText(text, { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '更多筛选' }).click()
  await page.getByRole('combobox', { name: '定义进度' }).selectOption('ready')
  await expect(page.getByRole('button', { name: '查看标签：均线金叉', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '移除筛选：已定义、待验证' }).click()
  await purposes.scrollIntoViewIfNeeded()
  await page.screenshot({ path: join(tmpdir(), `stock-definition-saved-${info.project.name}.png`) })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.getByRole('tab', { name: '版本历史', exact: true }).click()
  await page.getByRole('button', { name: '查看标签 v1', exact: true }).click()
  await expect(page.getByText('历史标签版本，只读', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '编辑用途与定义' })).toHaveCount(0)
  expect(errors).toEqual([])
})

test('dirty edits require explicit discard and pagination keeps the detail in the visible list', async ({ page }) => {
  await page.goto('/knowledge?view=notes')
  await page.getByRole('button', { name: '下一页', exact: true }).click()
  const list = page.getByRole('region', { name: '笔记目录', exact: true })
  await expect(list.getByRole('button', { name: /^查看标签：/ }).first()).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('textbox', { name: '搜索笔记与标签' }).fill('01-ma-golden-cross.md')
  await page.getByRole('button', { name: '编辑笔记', exact: true }).click()
  await page.getByRole('button', { name: '编辑用途与定义' }).click()
  const editor = page.getByRole('dialog')
  await editor.getByLabel('条件或计算方法').fill('尚未保存')
  await page.evaluate(() => window.history.back())
  await expect(editor.getByRole('button', { name: '继续编辑' })).toBeFocused()
  await editor.getByRole('button', { name: '继续编辑' }).click()
  await expect(editor.getByLabel('条件或计算方法')).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(editor.getByRole('button', { name: '放弃修改' })).toBeVisible()
  await editor.getByRole('button', { name: '继续编辑' }).click()
  await expect(editor.getByLabel('条件或计算方法')).toHaveValue('尚未保存')
  await editor.getByRole('button', { name: '取消定义编辑' }).click()
  await editor.getByRole('button', { name: '放弃修改' }).click()
  await expect(editor).not.toBeVisible()
  await expect(page.getByRole('button', { name: '编辑用途与定义' })).toBeVisible()
})

test('one definition editor adds another purpose and restores each saved definition', async ({ page }, info) => {
  await page.goto('/knowledge?view=notes')
  await page.getByRole('textbox', { name: '搜索笔记与标签' }).fill('01-ma-golden-cross.md')
  await page.getByRole('button', { name: '编辑笔记', exact: true }).click()
  await page.getByRole('button', { name: '编辑用途与定义', exact: true }).click()
  const editor = page.getByRole('dialog')
  await editor.getByLabel('条件或计算方法').fill('尚未保存的入场条件')
  await editor.getByRole('combobox', { name: '用途', exact: true }).selectOption('target')
  await editor.getByRole('button', { name: '继续编辑' }).click()
  await expect(editor.getByRole('combobox', { name: '用途', exact: true })).toHaveValue('entry')
  await expect(editor.getByLabel('条件或计算方法')).toHaveValue('尚未保存的入场条件')
  await editor.getByRole('combobox', { name: '用途', exact: true }).selectOption('target')
  await editor.getByRole('button', { name: '放弃修改' }).click()
  await expect(editor.getByLabel('条件或计算方法')).toHaveValue('')
  await editor.getByLabel('条件或计算方法').fill('参考前高压力位')
  await editor.getByRole('button', { name: '保存草稿' }).click()
  await expect(editor).not.toBeVisible()
  await page.getByRole('button', { name: '编辑用途与定义', exact: true }).click()
  await expect(editor.getByRole('combobox', { name: '用途', exact: true })).toHaveValue('entry')
  await expect(editor.getByLabel('条件或计算方法')).toHaveValue('')
  await editor.getByRole('combobox', { name: '用途', exact: true }).selectOption('target')
  await expect(editor.getByLabel('条件或计算方法')).toHaveValue('参考前高压力位')
  if (info.project.name === 'mobile') {
    await page.setViewportSize({ width: 812, height: 375 })
    await expect.poll(() => editor.getByRole('button', { name: '保存草稿', exact: true }).evaluate(element => element.getBoundingClientRect().height)).toBeGreaterThanOrEqual(44)
    expect((await editor.locator('.nt-editor-body').boundingBox())!.height).toBeGreaterThanOrEqual(100)
    const footer = (await editor.locator('footer').boundingBox())!
    expect(footer.y).toBeGreaterThanOrEqual(0)
    expect(footer.y + footer.height).toBeLessThanOrEqual(375)
    await page.screenshot({ path: info.outputPath('note-editor-landscape.png') })
  }
  await editor.getByRole('button', { name: '取消定义编辑' }).click()
  await expect(page.getByRole('button', { name: '编辑用途与定义', exact: true })).toBeFocused()
  await page.reload()
  await page.getByRole('textbox', { name: '搜索笔记与标签' }).fill('01-ma-golden-cross.md')
  await expect(page.getByText('参考前高压力位', { exact: true })).toBeVisible()
})
