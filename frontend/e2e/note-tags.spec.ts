import { expect, test } from './fixtures/test'

test.describe('source-backed note tags', () => {
  test('filters notes, revises tags, reloads history and exports source evidence', async ({ page }, info) => {
    const errors: string[] = []
    page.on('pageerror', (error) => errors.push(error.message))
    page.on('console', (message) => { if (message.type() === 'error' || message.type() === 'warning') errors.push(message.text()) })
    await page.goto('/knowledge?view=notes')
    await expect(page).toHaveTitle(/StockCal/)
    await expect(page.getByRole('heading', { name: '笔记标签目录' })).toBeVisible()
    await expect(page.getByRole('region', { name: '笔记标签工作台' })).toContainText('146 篇笔记')
    await page.getByText('研究范围与标签说明', { exact: true }).click()
    await expect(page.getByRole('link', { name: '掌阅科技 · 603533' })).toHaveAttribute('href', '/?symbol=603533')
    await page.getByText('研究范围与标签说明', { exact: true }).click()
    await page.screenshot({ path: `/tmp/stockcal-tags-${info.project.name}-initial.png`, fullPage: false })
    await page.getByRole('combobox', { name: '分析主题', exact: true }).selectOption('topic.ma')
    await page.getByRole('combobox', { name: '内容分类', exact: true }).selectOption('kind.screen')
    await expect(page.getByRole('region', { name: '笔记目录' })).not.toContainText('股票价格')
    await page.getByRole('textbox', { name: '搜索笔记与标签' }).fill('选股总结')
    await page.getByRole('button', { name: '查看标签：选股总结', exact: true }).click()
    const detail = page.getByRole('region', { name: '标签详情' })
    await detail.getByRole('tab', { name: '原文与依据' }).click()
    await expect(detail.getByRole('tabpanel', { name: '原文与依据' })).toContainText('20日线和5日线以上的个股')
    await detail.getByRole('button', { name: '编辑标签', exact: true }).click()
    const editor = page.getByRole('dialog', { name: '修订笔记标签' })
    await editor.getByRole('checkbox', { name: '卖出', exact: true }).check()
    await editor.getByLabel('修订原因', { exact: true }).fill('测试：补充卖出研究标签，保留原有解释。')
    await editor.getByRole('button', { name: '保存标签新版本', exact: true }).click()
    await expect(editor).not.toBeVisible()
    await expect(detail).toContainText('人工修订')
    await page.reload()
    await page.getByRole('textbox', { name: '搜索笔记与标签' }).fill('选股总结')
    await page.getByRole('button', { name: '查看标签：选股总结', exact: true }).click()
    await expect(detail).toContainText('测试：补充卖出研究标签')
    await detail.getByRole('tab', { name: '版本历史' }).click()
    await detail.getByRole('button', { name: '查看标签 v1', exact: true }).click()
    await expect(detail).toContainText('历史标签版本，只读')
    await expect(detail.getByRole('button', { name: '编辑标签', exact: true })).toHaveCount(0)
    await detail.getByRole('button', { name: '返回当前标签', exact: true }).click()
    const downloadPromise = page.waitForEvent('download')
    await page.getByRole('button', { name: '导出标签与历史', exact: true }).click()
    const download = await downloadPromise
    const path = `/tmp/stockcal-tags-${info.project.name}.json`
    await download.saveAs(path)
    const { readFile } = await import('node:fs/promises')
    const exported = JSON.parse(await readFile(path, 'utf8'))
    const versions = exported.records.filter((record: { id: string }) => record.id === 'note:选股总结.md')
    expect(versions.map((record: { version: number }) => record.version)).toEqual([1, 2])
    expect(versions[0].tags).not.toContain('topic.sell')
    expect(versions[1].tags).toContain('topic.sell')
    expect(versions[1].sourceHash).toBe(versions[0].sourceHash)
    expect(exported.taxonomy).toHaveLength(2)
    expect(exported.records.filter((record: { level: string }) => record.level === 'document')).toHaveLength(147)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
    await expect(page.locator('nextjs-portal').getByText(/Runtime Error|Build Error|Application error/)).toHaveCount(0)
    expect(errors).toEqual([])
    await detail.scrollIntoViewIfNeeded()
    await page.screenshot({ path: `/tmp/stockcal-tags-${info.project.name}.png`, fullPage: false })
  })
})
