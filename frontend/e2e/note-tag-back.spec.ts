import { expect, test } from './fixtures/test'

test('Back closes tag editing before leaving the selected note', async ({ page }) => {
  await page.goto('/')
  await page.evaluate(() => { window.location.href = '/knowledge?view=notes' })
  const edit = page.getByRole('button', { name: '标签与补充说明', exact: true })
  await expect(page.getByRole('button', { name: '编辑笔记', exact: true })).toBeEnabled({ timeout: 30000 })
  const search = page.getByRole('textbox', { name: '搜索笔记与标签', exact: true })
  await search.fill('金叉')
  await expect(page.getByRole('region', { name: '标签详情' })).toContainText('golden-cross')
  const title = await page.getByRole('region', { name: '标签详情' }).getByRole('heading', { level: 3 }).textContent()
  if (await page.getByRole('button', { name: '编辑笔记', exact: true }).count()) await page.getByRole('button', { name: '编辑笔记', exact: true }).click()
  await edit.click()
  const dialog = page.getByRole('dialog', { name: '修订笔记标签' })
  await expect(dialog).toBeVisible()
  await dialog.getByLabel('修订原因').fill('未保存草稿')
  await page.goBack()
  await expect(dialog).toHaveCount(0)
  await expect(page).toHaveURL(/\/knowledge\?view=notes$/)
  await expect(search).toHaveValue('金叉')
  await expect(page.getByRole('region', { name: '标签详情' }).getByRole('heading', { level: 3 })).toHaveText(title!)
  if (await page.getByRole('button', { name: '编辑笔记', exact: true }).count()) await page.getByRole('button', { name: '编辑笔记', exact: true }).click()
  await edit.click()
  await expect(dialog.getByLabel('修订原因')).toHaveValue('')
  await dialog.getByRole('button', { name: '取消标签编辑' }).click()
  await expect(dialog).toHaveCount(0)
  await expect.poll(() => page.evaluate(() => Boolean(history.state?.stockcalTagEditor))).toBe(false)
  await page.goBack()
  await expect(page).toHaveURL(/\/$/)
})
