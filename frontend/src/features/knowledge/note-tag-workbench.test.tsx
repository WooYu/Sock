import { fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import catalogData from './note-tag-catalog.json'
import { NoteTagWorkbench } from './note-tag-workbench'
import { NOTE_TAG_STORAGE_KEY, activeTagRecord, applyAIOriginalTags, currentTagRecords, parseTagLedger, reviewTags, type NoteCatalog } from './note-tags'

const complete = catalogData as NoteCatalog
const files = ['选股总结.md', '股票价格.md', '01-ma-golden-cross.md']
const fixture: NoteCatalog = { ...complete, documents: complete.documents.filter((record) => files.includes(record.file)), fragments: complete.fragments.filter((record) => files.includes(record.file)) }
beforeEach(() => localStorage.clear())
afterEach(() => vi.unstubAllGlobals())

describe('note tagging workbench', () => {
  it('separates reading views with keyboard navigation and resets when choosing another note', () => {
    render(<NoteTagWorkbench catalog={fixture} />)
    const overview = screen.getByRole('tab', { name: '概览' })
    expect(overview).toHaveAttribute('aria-selected', 'true')
    fireEvent.keyDown(overview, { key: 'ArrowRight' })
    const source = screen.getByRole('tab', { name: '原文与依据' })
    expect(source).toHaveFocus()
    expect(screen.getByRole('tabpanel', { name: '原文与依据' })).toBeVisible()
    expect(screen.queryByRole('tabpanel', { name: '概览' })).not.toBeInTheDocument()
    fireEvent.keyDown(source, { key: 'End' })
    expect(screen.getByRole('tabpanel', { name: '版本历史' })).toBeVisible()
    fireEvent.click(screen.getByRole('button', { name: '查看标签：选股总结' }))
    expect(overview).toHaveAttribute('aria-selected', 'true')
    expect(screen.getByRole('button', { name: '编辑标签' })).toBeVisible()
  })

  it('previews fresh dual-model results and appends a version only after editor save', async () => {
    const original = currentTagRecords(fixture.documents, [])[0]
    const candidate = { id: original.id, sourceHash: original.sourceHash, tags: ['topic.ma'], evidence: [{ ...original.evidence[0], tagId: 'topic.ma', method: 'ai', reason: '本次双模型提取' }], extraction: { models: ['DeepSeek', 'Codex'], note: '本次全文提取', disagreements: [{ tagId: 'topic.climb', model: 'DeepSeek' }] } }
    const fetchMock = vi.fn().mockResolvedValue(Response.json({ id: original.id, sourceHash: original.sourceHash, candidate, models: [{ name: 'DeepSeek', tags: ['topic.ma', 'topic.climb'] }, { name: 'Codex', tags: ['topic.ma'] }] }))
    vi.stubGlobal('fetch', fetchMock)
    render(<NoteTagWorkbench catalog={fixture} />)
    fireEvent.click(screen.getByRole('button', { name: 'AI 重新提取标签' }))
    await screen.findByRole('button', { name: '采用本次结果并编辑' })
    expect(screen.getByText('模型分歧（未采用）')).toBeInTheDocument()
    expect(parseTagLedger(localStorage.getItem(NOTE_TAG_STORAGE_KEY))).toHaveLength(0)
    expect(JSON.parse(fetchMock.mock.calls[0][1].body)).toEqual({ id: original.id, sourceHash: original.sourceHash })
    fireEvent.click(screen.getByRole('button', { name: '采用本次结果并编辑' }))
    let editor = screen.getByRole('dialog')
    expect(within(editor).getByRole('checkbox', { name: 'MA均线' })).toBeChecked()
    fireEvent.click(within(editor).getByRole('button', { name: '取消标签编辑' }))
    expect(parseTagLedger(localStorage.getItem(NOTE_TAG_STORAGE_KEY))).toHaveLength(0)
    fireEvent.click(screen.getByRole('button', { name: '采用本次结果并编辑' }))
    editor = screen.getByRole('dialog')
    fireEvent.click(within(editor).getByRole('button', { name: '保存标签新版本' }))
    const versions = parseTagLedger(localStorage.getItem(NOTE_TAG_STORAGE_KEY))
    expect(versions.map(item => item.version)).toEqual([1, 2])
    expect(versions[0].tags).toEqual(original.tags)
    expect(versions[1].tags).toEqual(candidate.tags)
    expect(versions[1].extraction?.note).toBe('本次全文提取')
  })
  it('shows partial extraction failure without offering consensus adoption', async () => {
    const original = currentTagRecords(fixture.documents, [])[0]
    vi.stubGlobal('fetch', vi.fn().mockResolvedValue(Response.json({ id: original.id, sourceHash: original.sourceHash, candidate: null, models: [{ name: 'DeepSeek', tags: ['topic.ma'] }, { name: 'Codex', error: 'Codex 未配置' }] })))
    render(<NoteTagWorkbench catalog={fixture} />)
    fireEvent.click(screen.getByRole('button', { name: 'AI 重新提取标签' }))
    await screen.findByText('Codex 未配置')
    expect(screen.queryByRole('button', { name: '采用本次结果并编辑' })).not.toBeInTheDocument()
    expect(parseTagLedger(localStorage.getItem(NOTE_TAG_STORAGE_KEY))).toHaveLength(0)
  })
  it('previews AI tag adoption and retains the actual previous manual version', () => {
    const original = fixture.documents[0]
    const reviewed = reviewTags(original, '2026-10-20T01:00:00Z')
    localStorage.setItem(NOTE_TAG_STORAGE_KEY, JSON.stringify({ schemaVersion: 1, records: [original, reviewed] }))
    const aiCatalog = applyAIOriginalTags(fixture, [{ id: original.id, sourceHash: original.sourceHash, tags: ['topic.ma'], evidence: [{ ...original.evidence[0], tagId: 'topic.ma', method: 'ai' }], extraction: { models: ['DeepSeek', 'Codex'], note: '仅保留核心主题', disagreements: [] } }])
    render(<NoteTagWorkbench catalog={aiCatalog} />)
    fireEvent.click(screen.getByRole('tab', { name: '原文与依据' }))
    fireEvent.click(screen.getByText('AI 提取说明'))
    fireEvent.click(screen.getByRole('button', { name: '采用 AI 精简标签' }))
    const editor = screen.getByRole('dialog')
    expect(within(editor).getByRole('checkbox', { name: 'MA均线' })).toBeChecked()
    expect(within(editor).queryByRole('checkbox', { name: 'MA5' })).not.toBeInTheDocument()
    expect(parseTagLedger(localStorage.getItem(NOTE_TAG_STORAGE_KEY))).toHaveLength(2)
    fireEvent.click(within(editor).getByRole('button', { name: '保存标签新版本' }))
    const versions = parseTagLedger(localStorage.getItem(NOTE_TAG_STORAGE_KEY))
    expect(versions).toHaveLength(3)
    expect(versions[1].tags).toEqual(reviewed.tags)
    expect(versions[2].tags).toEqual(['topic.ma'])
    expect(versions[2].evidence[0].method).toBe('ai')
  })
  it('previews supplementary suggestions before applying and saves them in one version', async () => {
    vi.stubGlobal('fetch', vi.fn().mockResolvedValue(Response.json({ suggestions: [{ tagId: 'topic.sell', action: 'add', quote: '卖出研究', reason: '用户补充卖出主题', conflict: '原文未说明卖出' }] })))
    const view = render(<NoteTagWorkbench catalog={fixture} />)
    fireEvent.click(screen.getByRole('button', { name: '补充说明' }))
    const editor = screen.getByRole('dialog')
    expect(within(editor).getByLabelText('补充说明')).toHaveFocus()
    fireEvent.change(within(editor).getByLabelText('补充说明'), { target: { value: '增加卖出研究' } })
    fireEvent.click(within(editor).getByRole('button', { name: '根据说明建议标签' }))
    await screen.findByText('待确认的标签变化')
    expect(within(editor).getByRole('checkbox', { name: '卖出' })).not.toBeChecked()
    fireEvent.click(within(editor).getByRole('checkbox', { name: /新增 · 卖出/ }))
    fireEvent.click(within(editor).getByRole('button', { name: '应用所选建议到勾选标签' }))
    expect(within(editor).getByRole('checkbox', { name: '卖出' })).toBeChecked()
    fireEvent.click(within(editor).getByRole('button', { name: '保存标签新版本' }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    const saved = parseTagLedger(localStorage.getItem(NOTE_TAG_STORAGE_KEY))
    expect(saved).toHaveLength(2)
    expect(saved[1].supplementEvidence?.[0].quote).toBe('卖出研究')
    view.unmount()
    render(<NoteTagWorkbench catalog={fixture} />)
    expect(screen.getByText('增加卖出研究')).toBeInTheDocument()
  })
  it('opens the selected original from both the catalog and detail heading', () => {
    render(<NoteTagWorkbench catalog={fixture} />)
    const record = currentTagRecords(fixture.documents, [])[0]
    const link = screen.getByRole('link', { name: `查看原文：${record.title}` })
    expect(link).toHaveAttribute('href', record.sourceUrl)
    expect(link).toHaveAttribute('target', '_blank')
    expect(within(screen.getByRole('region', { name: '标签详情' })).getByRole('link', { name: '查看原文 ↗' })).toHaveAttribute('href', record.sourceUrl)
  })
  it('combines topic and usage filters and can inspect rule fragments', async () => {
    const user = userEvent.setup()
    render(<NoteTagWorkbench catalog={fixture} />)
    const list = screen.getByRole('region', { name: '笔记目录' })
    await user.selectOptions(screen.getByLabelText('分析主题'), 'topic.ma')
    await user.selectOptions(screen.getByLabelText('内容分类'), 'kind.screen')
    expect(within(list).getByRole('button', { name: '查看标签：选股总结' })).toBeInTheDocument()
    expect(within(list).queryByRole('button', { name: '查看标签：股票价格' })).not.toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: '重置标签筛选' }))
    await user.selectOptions(screen.getByLabelText('标注层级'), 'fragment')
    await user.type(screen.getByRole('textbox', { name: '搜索笔记与标签' }), '金叉')
    expect(within(list).getByRole('button', { name: '查看标签：均线金叉' })).toBeInTheDocument()
  })

  it('saves tag revisions with reasons, restores them after reload and retains the old source and tags', async () => {
    const user = userEvent.setup()
    const view = render(<NoteTagWorkbench catalog={fixture} />)
    await user.click(screen.getByRole('button', { name: '查看标签：选股总结' }))
    const details = screen.getByRole('region', { name: '标签详情' })
    await user.click(within(details).getByRole('button', { name: '编辑标签' }))
    const editor = screen.getByRole('dialog', { name: '修订笔记标签' })
    await user.click(within(editor).getByRole('checkbox', { name: '卖出' }))
    await user.type(within(editor).getByLabelText('修订原因'), '另按卖出研究；保留原有日线解释。')
    await user.click(within(editor).getByRole('button', { name: '保存标签新版本' }))
    await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
    const versions = parseTagLedger(localStorage.getItem(NOTE_TAG_STORAGE_KEY))
    expect(versions).toHaveLength(2)
    expect(versions[0].tags).not.toContain('topic.sell')
    expect(versions[1].tags).toContain('topic.sell')
    expect(versions[1].sourceHash).toBe(versions[0].sourceHash)
    expect(versions[1].sourceExcerpt).toBe(versions[0].sourceExcerpt)
    expect(versions[1].revisionReason).toContain('另按卖出研究')
    view.unmount()
    render(<NoteTagWorkbench catalog={fixture} />)
    await user.click(screen.getByRole('button', { name: '查看标签：选股总结' }))
    expect(screen.getByRole('region', { name: '标签详情' })).toHaveTextContent('人工修订')
    await user.click(screen.getByRole('tab', { name: '版本历史' }))
    await user.click(screen.getByRole('button', { name: '查看标签 v1' }))
    expect(screen.getByText('历史标签版本，只读')).toBeInTheDocument()
    expect(within(screen.getByRole('region', { name: '标签详情' })).queryByRole('button', { name: '编辑标签' })).not.toBeInTheDocument()
  })

  it('preserves corrupt local records and disables writes until they can be recovered', async () => {
    localStorage.setItem(NOTE_TAG_STORAGE_KEY, '{broken')
    render(<NoteTagWorkbench catalog={fixture} />)
    expect(await screen.findByRole('alert')).toHaveTextContent('未被覆盖')
    expect(screen.getByRole('button', { name: '编辑标签' })).toBeDisabled()
    expect(localStorage.getItem(NOTE_TAG_STORAGE_KEY)).toBe('{broken')
  })

  it('records tag review without upgrading computation readiness or clearing missing definitions', async () => {
    render(<NoteTagWorkbench catalog={fixture} />)
    await screen.findByRole('button', { name: '确认标签' })
    fireEvent.click(screen.getByRole('button', { name: '确认标签' }))
    const versions = parseTagLedger(localStorage.getItem(NOTE_TAG_STORAGE_KEY))
    expect(versions.at(-1)?.status).toBe('reviewed')
    expect(versions.at(-1)?.tags).toEqual(activeTagRecord(versions[0]).tags)
    expect(versions.at(-1)?.gaps).toEqual(versions[0].gaps)
    expect(screen.getByText(/标签核对不代表计算定义或预测效果已验证/)).toBeInTheDocument()
  })
})
