import { fireEvent, render, screen, within } from '@testing-library/react'
import { describe, expect, it, vi } from 'vitest'
import { ForecastDefinitionEditor } from './note-forecast-definition-editor'

describe('forecast definition editor', () => {
  it('switches purposes directly, but protects dirty input until discard is confirmed', () => {
    const changeRole = vi.fn(), cancel = vi.fn()
    render(<ForecastDefinitionEditor role="entry" title="示例笔记" onRoleChange={changeRole} onSave={vi.fn()} onCancel={cancel} error="" />)
    fireEvent.change(screen.getByLabelText('用途', { exact: true }), { target: { value: 'target' } })
    expect(changeRole).toHaveBeenCalledWith('target')
    changeRole.mockClear()
    fireEvent.change(screen.getByLabelText('条件或计算方法'), { target: { value: '保留这段条件' } })
    fireEvent.change(screen.getByLabelText('用途', { exact: true }), { target: { value: 'exit' } })
    expect(changeRole).not.toHaveBeenCalled()
    expect(screen.getByRole('alert')).toHaveTextContent('切换用途')
    fireEvent.click(screen.getByRole('button', { name: '继续编辑' }))
    expect(screen.getByLabelText('用途', { exact: true })).toHaveValue('entry')
    expect(screen.getByLabelText('条件或计算方法')).toHaveValue('保留这段条件')
    fireEvent.change(screen.getByLabelText('用途', { exact: true }), { target: { value: 'exit' } })
    fireEvent.click(screen.getByRole('button', { name: '放弃修改' }))
    expect(changeRole).toHaveBeenCalledWith('exit')
    expect(cancel).not.toHaveBeenCalled()
  })
  it('closes instead of switching when escape follows a pending purpose change', () => {
    const changeRole = vi.fn(), cancel = vi.fn()
    render(<ForecastDefinitionEditor role="entry" title="示例笔记" onRoleChange={changeRole} onSave={vi.fn()} onCancel={cancel} error="" />)
    fireEvent.change(screen.getByLabelText('条件或计算方法'), { target: { value: '未保存条件' } })
    fireEvent.change(screen.getByLabelText('用途', { exact: true }), { target: { value: 'exit' } })
    fireEvent.keyDown(screen.getByRole('dialog'), { key: 'Escape' })
    fireEvent.click(screen.getByRole('button', { name: '放弃修改' }))
    expect(cancel).toHaveBeenCalledOnce()
    expect(changeRole).not.toHaveBeenCalled()
  })
  it('returns focus to the opening control after the editor closes', () => {
    const trigger = document.createElement('button')
    document.body.append(trigger)
    trigger.focus()
    const view = render(<ForecastDefinitionEditor role="target" title="示例笔记" onSave={vi.fn()} onCancel={vi.fn()} error="" />)
    view.unmount()
    expect(trigger).toHaveFocus()
    trigger.remove()
  })
  it('saves partial content as a draft and prevents incomplete completion', () => {
    const save = vi.fn()
    render(<ForecastDefinitionEditor role="target" title="示例笔记" onSave={save} onCancel={vi.fn()} error="" />)
    fireEvent.change(screen.getByLabelText('条件或计算方法'), { target: { value: '参考上轨' } })
    fireEvent.click(screen.getByRole('button', { name: '保存并标记待验证' }))
    expect(save).not.toHaveBeenCalled()
    expect(screen.getByRole('alert')).toHaveTextContent('适用周期')
    fireEvent.click(screen.getByRole('button', { name: '保存草稿' }))
    expect(save).toHaveBeenCalledWith(expect.objectContaining({ role: 'target', state: 'draft', condition: '参考上轨' }), expect.any(String))
  })
  it('keeps dirty input until discard is explicitly chosen, and preserves input on save error', () => {
    const cancel = vi.fn()
    const { rerender } = render(<ForecastDefinitionEditor role="context" title="示例笔记" onSave={vi.fn()} onCancel={cancel} error="" />)
    fireEvent.change(screen.getByLabelText('适用场景'), { target: { value: '震荡区间' } })
    fireEvent.keyDown(screen.getByRole('dialog'), { key: 'Escape' })
    expect(cancel).not.toHaveBeenCalled()
    expect(screen.getByRole('button', { name: '继续编辑' })).toHaveFocus()
    fireEvent.click(screen.getByRole('button', { name: '继续编辑' }))
    expect(screen.getByLabelText('条件或计算方法')).toHaveFocus()
    rerender(<ForecastDefinitionEditor role="context" title="示例笔记" onSave={vi.fn()} onCancel={cancel} error="保存失败：输入已保留。" />)
    expect(screen.getByLabelText('适用场景')).toHaveValue('震荡区间')
    expect(screen.getByRole('alert')).toHaveTextContent('保存失败')
    fireEvent.click(screen.getByRole('button', { name: '取消定义编辑' }))
    fireEvent.click(screen.getByRole('button', { name: '放弃修改' }))
    expect(cancel).toHaveBeenCalledOnce()
  })
  it('submits complete definitions as ready, while explaining that validation is separate', () => {
    const save = vi.fn()
    render(<ForecastDefinitionEditor role="entry" title="示例笔记" onSave={save} onCancel={vi.fn()} error="" />)
    for (const label of ['条件或计算方法', '适用周期', '适用场景', '失效或退出条件']) fireEvent.change(screen.getByLabelText(label), { target: { value: `${label}的定义` } })
    fireEvent.click(screen.getByRole('button', { name: '保存并标记待验证' }))
    expect(save).toHaveBeenCalledWith(expect.objectContaining({ state: 'ready' }), expect.any(String))
    expect(within(screen.getByRole('dialog')).getByText(/不会自动启用公式/)).toBeVisible()
  })
  it('intercepts browser back for dirty definitions instead of silently losing changes', () => {
    const cancel = vi.fn()
    window.history.pushState({ stockcalDefinitionEditor: true }, '')
    render(<ForecastDefinitionEditor role="entry" title="示例笔记" onSave={vi.fn()} onCancel={cancel} error="" />)
    expect(window.history.state?.stockcalDefinitionEditor).toBeTruthy()
    fireEvent.change(screen.getByLabelText('条件或计算方法'), { target: { value: '未保存的条件' } })
    fireEvent.popState(window)
    expect(cancel).not.toHaveBeenCalled()
    expect(screen.getByRole('button', { name: '继续编辑' })).toBeVisible()
    expect(screen.getByLabelText('条件或计算方法')).toHaveValue('未保存的条件')
  })
})
